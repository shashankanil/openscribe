import AppKit

/// Watches the Mac clipboard for text the user copies, and writes text that arrives from the phone.
/// macOS has no change notification, so it polls `changeCount`, which is a cheap integer read.
@MainActor
final class ClipboardBridge {
    /// Pasteboard types apps set on content that should not leave the Mac or outlive the moment
    /// (see nspasteboard.org): password managers, and OpenScribe's own paste injection.
    nonisolated static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]
    /// Marks text written from the phone so it is not sent straight back.
    nonisolated static let fromPhoneType = NSPasteboard.PasteboardType("org.open-source.openscribe.phone-link")

    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private var lastText: String?
    private var lastImageHash: Int?
    private var timer: Timer?
    var onCopy: ((String) -> Void)?
    /// Set only while images can be shared (signed in to OpenScribe Cloud); otherwise images are never read.
    var onCopyImage: ((Data, String) -> Void)?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    var isWatching: Bool { timer != nil }

    func startWatching() {
        guard timer == nil else { return }
        // Only copies made from now on are sent, never whatever was already on the clipboard.
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stopWatching() {
        timer?.invalidate()
        timer = nil
    }

    func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let types = pasteboard.types ?? []
        if let text = Self.shareableText(types: types, string: pasteboard.string(forType: .string)) {
            guard text != lastText else { return }
            lastText = text
            onCopy?(text)
            return
        }
        // An image with no text (a screenshot, an image copied from a browser or Preview).
        guard let onCopyImage, Self.isShareableImage(types: types), let image = ClipboardImage.read(from: pasteboard) else { return }
        let hash = image.data.hashValue
        guard hash != lastImageHash else { return }
        lastImageHash = hash
        onCopyImage(image.data, image.mime)
    }

    nonisolated static func isShareableImage(types: [NSPasteboard.PasteboardType]) -> Bool {
        !types.contains(where: { privateTypes.contains($0) || $0 == fromPhoneType }) && types.contains(where: ClipboardImage.types.contains)
    }

    /// Text that may be sent to the phone, or nil for private, phone-originated, empty or oversized content.
    nonisolated static func shareableText(types: [NSPasteboard.PasteboardType], string: String?) -> String? {
        guard !types.contains(where: { privateTypes.contains($0) || $0 == fromPhoneType }),
              let string, !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              string.utf8.count <= PhoneLinkProtocol.maxClipboardBytes else { return nil }
        return string
    }

    /// Text that was just sent another way, so the next poll doesn't send it again.
    func noteSent(_ text: String) {
        lastText = text
        lastChangeCount = pasteboard.changeCount
    }

    /// Puts an image from the phone on the Mac clipboard.
    func writeImage(_ data: Data, mime: String) {
        let type: NSPasteboard.PasteboardType = mime == "image/png" ? .png : NSPasteboard.PasteboardType("public.jpeg")
        pasteboard.clearContents()
        pasteboard.declareTypes([type, .tiff, Self.fromPhoneType], owner: nil)
        pasteboard.setData(data, forType: type)
        // TIFF too, for apps that only paste that.
        if let tiff = NSBitmapImageRep(data: data)?.tiffRepresentation { pasteboard.setData(tiff, forType: .tiff) }
        pasteboard.setData(Data(), forType: Self.fromPhoneType)
        lastChangeCount = pasteboard.changeCount
        lastImageHash = data.hashValue
    }

    /// Puts text from the phone on the Mac clipboard.
    func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.declareTypes([.string, Self.fromPhoneType], owner: nil)
        pasteboard.setString(text, forType: .string)
        pasteboard.setData(Data(), forType: Self.fromPhoneType)
        lastChangeCount = pasteboard.changeCount
        lastText = text
    }
}
